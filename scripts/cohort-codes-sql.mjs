// One single-use membership code per student. See docs/MEMBER_ONBOARDING.md, step 2b.
//   node scripts/cohort-codes-sql.mjs AU26 private/roster.csv > private/codes.sql

import { readFileSync } from "node:fs";

const VALID_FOR = "14 days";
const EMAIL = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;

const [cohort, path] = process.argv.slice(2);
if (!cohort || !path) {
  console.error("usage: node scripts/cohort-codes-sql.mjs <cohort> <roster.csv>");
  process.exit(1);
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') {
        quoted = false;
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += ch;
    }
  }
  if (field || row.length) rows.push([...row, field]);
  return rows.filter((r) => r.some((c) => c.trim()));
}

const sql = (s) => `'${s.replaceAll("'", "''")}'`;

const [header, ...rows] = parseCsv(readFileSync(path, "utf8").replace(/^\uFEFF/, ""));
const col = (name) => {
  const i = header.findIndex((h) => h.trim().toLowerCase() === name);
  if (i === -1) throw new Error(`roster is missing a "${name}" column`);
  return i;
};
const [first, last, email] = ["first name", "last name", "osu email"].map(col);

const seen = new Set();
const students = rows.map((r, n) => {
  const s = {
    first: r[first]?.trim() ?? "",
    last: r[last]?.trim() ?? "",
    email: r[email]?.trim().toLowerCase() ?? "",
  };
  const line = n + 2;
  if (!s.first || !s.last) throw new Error(`line ${line}: missing a name`);
  if (!EMAIL.test(s.email)) throw new Error(`line ${line}: "${s.email}" is not an email`);
  if (seen.has(s.email)) throw new Error(`line ${line}: ${s.email} appears twice`);
  seen.add(s.email);
  return s;
});

const values = students
  .map((s) => `    (${sql(s.first)}, ${sql(s.last)}, ${sql(s.email)}, ${sql(`${cohort} member: ${s.email}`)})`)
  .join(",\n");

process.stdout.write(`-- ${students.length} students, cohort ${cohort}. Generated by scripts/cohort-codes-sql.mjs.
with roster (first_name, last_name, email, label) as (
  values
${values}
)
select r.first_name,
       r.last_name,
       r.email,
       public.issue_invite_code(r.label, 1, interval ${sql(VALID_FOR)}) as code,
       -- Day before expiry, Columbus time, so "good until" is never late.
       to_char((now() + interval ${sql(VALID_FOR)} - interval '1 day') at time zone 'America/New_York', 'Mon FMDD, YYYY') as expires_on
  from roster r
 where not exists (
         select 1
           from public.invite_codes c
          where c.label = r.label
            and c.revoked_at is null
            and c.expires_at > now()
       )
 order by r.last_name, r.first_name;
`);
